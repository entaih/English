#!/usr/bin/env node
// Builds the runtime content bundles from content/src/*.json.
//   content/catalog.js        lesson list, topics, order (small, loaded first)
//   content/levels/<L>.js     every lesson's variant at level L (loaded on demand)
// Usage: node tools/build.mjs [--check]   (--check fails if output is stale)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { validateLesson } from "./validate.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LEVELS = ["A1", "A2", "B1", "B2", "C1", "C2"];
const check = process.argv.includes("--check");
const partial = process.argv.includes("--partial"); // dev only: skip lessons that are not written yet
const cur = JSON.parse(fs.readFileSync(path.join(ROOT, "content/curriculum.json"), "utf8"));
const srcDir = path.join(ROOT, "content/src");
const lessons = {};
let failed = false;
for (const id of cur.order) {
  const f = path.join(srcDir, id + ".json");
  if (!fs.existsSync(f)) { if (!partial) { console.error(`missing ${id}.json`); failed = true; } continue; }
  const L = JSON.parse(fs.readFileSync(f, "utf8"));
  const { errors } = validateLesson(L, f);
  if (errors.length) { console.error(`${id}: ${errors.length} errors (run tools/validate.mjs)`); failed = true; continue; }
  lessons[id] = L;
}
const extra = fs.readdirSync(srcDir).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).filter((id) => !cur.order.includes(id));
if (extra.length) { console.error(`not in curriculum order: ${extra.join(", ")}`); failed = true; }
if (failed) process.exit(1);

if (partial) cur.order = cur.order.filter((id) => lessons[id]);
const header = "/* Generated by tools/build.mjs from content/src. Do not edit by hand. */\n";
const out = {};
const catalog = {
  topics: cur.topics,
  order: cur.order,
  lessons: Object.fromEntries(cur.order.map((id) => {
    const L = lessons[id];
    return [id, { id, topic: L.topic, title: L.title, titleTr: L.titleTr,
      size: Object.fromEntries(LEVELS.map((lv) => [lv, L.levels[lv].text.length])) }];
  }))
};
out["content/catalog.js"] = header + "window.CATALOG = " + JSON.stringify(catalog) + ";\n";
for (const lv of LEVELS) {
  const data = Object.fromEntries(cur.order.map((id) => [id, lessons[id].levels[lv]]));
  out[`content/levels/${lv}.js`] = header + "window.LEVEL_DATA = window.LEVEL_DATA || {};\nwindow.LEVEL_DATA[" + JSON.stringify(lv) + "] = " + JSON.stringify(data) + ";\n";
}
let stale = [];
for (const [rel, text] of Object.entries(out)) {
  const p = path.join(ROOT, rel);
  const prev = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null;
  if (prev !== text) {
    stale.push(rel);
    if (!check) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, text); }
  }
}
if (check) {
  if (stale.length) { console.error("Content bundles are out of date: " + stale.join(", ") + "\nRun: node tools/build.mjs"); process.exit(1); }
  console.log("Content bundles are up to date.");
} else {
  const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0) + " KB";
  for (const [rel, text] of Object.entries(out)) console.log(`${stale.includes(rel) ? "wrote" : "same "} ${rel} ${kb(text)}`);
  console.log(`${cur.order.length} lessons × ${LEVELS.length} levels`);
}
